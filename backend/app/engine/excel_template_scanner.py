"""Excel template scanner — classify an uploaded .xlsx so a report can later be
regenerated from it safely.

This module is deliberately PURE: it takes a workbook (or a path) and returns a
plain-dict description. It never touches Snowflake, the filesystem beyond the one
file it is asked to read, or any other project module — so it is trivially
unit-testable and cannot affect the existing query/safety paths.

Nothing in this module is specific to any particular template, sheet, column, or
cell name. Detection is purely structural (formula shape + reference offsets).

Jobs:

1. Sheet roles — "formula" / "parameter" / "data" from the formula-vs-value mix.

2. Formula tiers:
     - Tier 1  (auto-regenerate): an aggregate (SUM/SUMIF/SUMIFS/COUNTIF/
       COUNTIFS/AVERAGEIF/SUMPRODUCT) over a multi-cell RANGE. Re-extend the
       range to a new row count.
     - Tier 1b (auto-regenerate, NEW): a "row-mirror block" — a contiguous
       vertical run of cells in one column where each cell's formula is the cell
       above it with every relative row reference shifted by exactly +1 (Excel
       fill-down). This is how a template lays one output row per data row. It is
       regenerated by extending/shrinking the block to the new row count,
       reproducing the shifted-reference pattern. Detected structurally, so a
       block is ONE unit — never one Tier-2 flag per cell per row.
     - Tier 2  (one-time human review): anything not provably safe — a single
       fixed cross-sheet cell reference, a lookup, an unrecognized function, or a
       vertical run whose per-row offset is NOT a clean +1 (a fragile hand-wired
       reference). Flagged, never auto-rewritten.
     - Tier 3  (static): self-contained cells with no ranges and no cross-sheet
       references. Left exactly as-is.

3. Fingerprint — sha256 over (sheet names + header rows + every formula's pattern
   with row numbers normalized away). Invariant to data-row count, so the same
   template shape matches a previously approved fingerprint.
"""

from __future__ import annotations

import hashlib
import re
from collections import defaultdict
from datetime import date, datetime, time
from typing import Any

import openpyxl
from openpyxl.utils import column_index_from_string, get_column_letter

try:  # array/table formulas come back as wrapper objects, not plain strings
    from openpyxl.worksheet.formula import ArrayFormula, DataTableFormula
    _FORMULA_WRAPPERS: tuple[type, ...] = (ArrayFormula, DataTableFormula)
except Exception:  # pragma: no cover - very old openpyxl
    _FORMULA_WRAPPERS = ()

# --- classification thresholds (heuristic; documented so they can be tuned) ---
FORMULA_SHEET_RATIO = 0.15   # >= this share of populated cells are formulas -> "formula"
MIN_MIRROR_ROWS = 3          # a row-mirror block must be at least this many rows
# A fill-down does not have to land on every row: a layout that prints one
# record per two or three rows (a spacer row, a sub-line beneath each record)
# is the same pattern with a gap. Beyond three rows the gap stops being a
# layout and starts being two unrelated cells that happen to rhyme.
MAX_ROW_STEP = 3
# Two rows is not evidence of a fill-down on its own. The SAME two rows
# repeated across a run of adjacent columns is, so a wide region is allowed to
# be shorter than a single column would have to be.
MIN_GROUP_COLUMNS = 3
MIN_WIDE_MIRROR_ROWS = 2
# A "data" tab = a header row followed by a contiguous block of >= this many
# record rows whose columns are type-consistent going DOWN. A "parameter" tab
# (scattered label/value pairs, section headers, blank rows, a type-mixed value
# column — a fund-parameters/config sheet) fails one of these and is not "data".
MIN_DATA_TABLE_ROWS = 3
# ...unless the header is wide. A TEMPLATE'S data sheet is refilled at run time,
# so it ships with however many sample rows somebody left in it — the servicer
# report has two. A wide header of distinct labels is what makes it a table;
# the rows below are a sample, not the evidence. A label/value parameter sheet
# is two or three columns wide, so this cannot let one through.
WIDE_HEADER_COLUMNS = 8
MIN_WIDE_TABLE_ROWS = 1
DATA_COL_CONSISTENCY = 0.75  # fraction of header columns that must be type-consistent

# Aggregate functions considered safe to auto-regenerate over a range (Tier 1).
# Each one summarises whatever rows its range covers, so extending the range to
# a new row count means exactly what it meant before.
SAFE_AGG_FUNCTIONS = frozenset({
    "SUM", "SUMIF", "SUMIFS", "SUMPRODUCT",
    "COUNT", "COUNTA", "COUNTIF", "COUNTIFS", "COUNTBLANK",
    "AVERAGE", "AVERAGEIF", "AVERAGEIFS",
    "MIN", "MINIFS", "MAX", "MAXIFS", "MEDIAN",
    "STDEV", "STDEV.S", "STDEV.P", "STDEVP", "VAR", "VAR.S", "VAR.P", "VARP",
})

# Functions that take a range and mean something OTHER than "summarise these
# rows": they pick a position, look a value up, or build a reference. Extending
# their range changes which row is picked, so a formula containing one is never
# auto-regenerated however safe the rest of it looks.
POSITIONAL_FUNCTIONS = frozenset({
    "INDEX", "MATCH", "XMATCH", "VLOOKUP", "HLOOKUP", "XLOOKUP", "LOOKUP",
    "OFFSET", "INDIRECT", "ROW", "ROWS", "COLUMN", "COLUMNS", "TRANSPOSE",
    "FILTER", "SORT", "SORTBY", "UNIQUE", "TAKE", "DROP", "CHOOSE", "CHOOSEROWS",
    "SUBTOTAL", "AGGREGATE", "LARGE", "SMALL", "RANK", "RANK.EQ", "PERCENTILE",
    "PERCENTILE.INC", "QUARTILE", "FREQUENCY", "ADDRESS", "CELL",
})

_FUNC_RE = re.compile(r"([A-Z][A-Z0-9.]*)\s*\(")
# A1:B2, $A$1:$B$2, or whole-column A:A / row 1:1 ranges.
_RANGE_RE = re.compile(r"\$?[A-Za-z]{1,3}\$?\d*:\$?[A-Za-z]{1,3}\$?\d*")
# A sheet-qualified reference: Sheet1! or 'My Sheet'! before a cell/range.
_CROSS_SHEET_RE = re.compile(r"(?:'[^']+'|[A-Za-z_][A-Za-z0-9_.]*)!")
# The same thing with the NAME captured, so it can be replaced by the sheet's
# position (see _shape_fingerprint).
_SHEET_QUALIFIER_RE = re.compile(
    r"(?<![#A-Za-z0-9_])(?:'([^']+)'|([A-Za-z_][A-Za-z0-9_.]*))!"
)
# A sheet-qualified SINGLE cell (Sheet1!B5) — used to spot formulas pinned to one record.
_CROSS_SHEET_CELL_RE = re.compile(
    r"(?:'[^']+'|[A-Za-z_][A-Za-z0-9_.]*)!\$?[A-Za-z]{1,3}\$?\d+"
)
_DIGITS_RE = re.compile(r"\d+")

# One A1-style cell reference (optionally sheet-qualified, optionally $-absolute),
# anchored so it is a whole token and NOT a function name like LOG10( .
_CELL_REF_RE = re.compile(
    r"(?<![A-Za-z0-9_$])"
    r"(?P<sheet>(?:'[^']+'|[A-Za-z_][A-Za-z0-9_.]*)!)?"
    r"(?P<colabs>\$?)(?P<col>[A-Za-z]{1,3})(?P<rowabs>\$?)(?P<row>\d+)"
    r"(?![A-Za-z0-9_(])"
)


def shift_formula_rows(formula: str, delta: int) -> str:
    """Return `formula` with every RELATIVE row number in every A1-style cell
    reference shifted by `delta` (Excel fill-down). Absolute rows ($3) and every
    non-reference number (thresholds, multipliers) are left unchanged."""
    def _repl(m: re.Match) -> str:
        if m.group("rowabs") == "$":            # absolute row: never shifts
            return m.group(0)
        new_row = int(m.group("row")) + delta
        if new_row < 1:                          # can't shift above row 1
            return m.group(0)
        return f"{m.group('sheet') or ''}{m.group('colabs')}{m.group('col')}" \
               f"{m.group('rowabs')}{new_row}"

    return _CELL_REF_RE.sub(_repl, formula)


def _row_shift(earlier: str, later: str) -> int | None:
    """How many rows `later` is `earlier` filled down by, or None if it is not a
    clean fill-down of it at all.

    Read from the formulas rather than from where the two cells sit, because
    those are not always the same number: a layout printing one record every
    second row shifts its references by one while its cells step by two."""
    rows_a = [int(m.group("row")) for m in _CELL_REF_RE.finditer(earlier)
              if m.group("rowabs") != "$"]
    rows_b = [int(m.group("row")) for m in _CELL_REF_RE.finditer(later)
              if m.group("rowabs") != "$"]
    if not rows_a or len(rows_a) != len(rows_b):
        return None
    delta = rows_b[0] - rows_a[0]
    if delta == 0 or any(b - a != delta for a, b in zip(rows_a, rows_b)):
        return None
    return delta if shift_formula_rows(earlier, delta) == later else None


def _shape(formula: str) -> str:
    """The formula's structural shape, with row numbers (and any literal digits)
    normalized away: `=D!K3` and `=D!K4` share a shape; `=SUM(E6:E10)` does not."""
    return _DIGITS_RE.sub("#", formula)


def fixed_record_refs(formula: str) -> list[str]:
    """Sheet-qualified SINGLE-cell references in a formula (ranges removed first).

    This is the risk signal that actually matters to a human reviewer: a formula
    holding one of these is pinned to ONE specific record. If the data's row count
    or order changes, it silently reads a DIFFERENT record — no error, just a wrong
    number. Aggregates over ranges (which we re-extend) don't have this problem."""
    body = formula[1:] if formula.startswith("=") else formula
    return _CROSS_SHEET_CELL_RE.findall(_RANGE_RE.sub("", body))


def _formula_text(cell) -> str | None:
    """Return the formula text for a cell, or None if it isn't a formula."""
    value = cell.value
    if _FORMULA_WRAPPERS and isinstance(value, _FORMULA_WRAPPERS):
        text = getattr(value, "text", None) or getattr(value, "ref", None) or ""
        return str(text)
    if cell.data_type == "f" and isinstance(value, str):
        return value
    if isinstance(value, str) and value.startswith("="):
        return value
    return None


def aggregated_ranges(formula: str) -> tuple[list[str], list[str]]:
    """Split a formula's ranges into (inside a safe aggregate, everywhere else).

    What decides whether a formula survives a change in row count is not which
    functions it mentions but what reads its RANGES. `IFERROR(SUMIFS(D:D, ...
    ">="&EDATE(A1,-6)), 0)` is a sum over a range with a wrapper and a date
    around it — extending the range means what it always meant. Judged on
    function names alone it is three unrecognised functions and a refusal.

    The scan walks the formula, tracking which function call each range sits
    inside, so a range's meaning comes from the function that reads it.
    """
    body = formula[1:] if formula.startswith("=") else formula
    inside: list[str] = []
    outside: list[str] = []

    # Which function call each character sits inside, innermost last.
    stack: list[str] = []
    pos = 0
    while pos < len(body):
        call = _FUNC_RE.match(body, pos) or _FUNC_RE.match(body.upper(), pos)
        if call and call.start() == pos:
            stack.append(call.group(1).upper())
            pos = call.end()
            continue
        char = body[pos]
        if char == "(":
            stack.append("")        # a bare bracket, not a call
            pos += 1
            continue
        if char == ")":
            if stack:
                stack.pop()
            pos += 1
            continue
        found = _RANGE_RE.match(body, pos)
        if found:
            (inside if any(f in SAFE_AGG_FUNCTIONS for f in stack) else outside).append(
                found.group(0)
            )
            pos = found.end()
            continue
        pos += 1
    return inside, outside


def classify_formula(formula: str) -> tuple[str, str, dict[str, Any]]:
    """Sort ONE formula (in isolation) into a tier. Returns (tier, reason, meta).

    Note this never returns tier_1b — row-mirror is a property of a *run* of
    cells, decided by detect_row_mirror_blocks, not of a single formula."""
    body = formula[1:] if formula.startswith("=") else formula
    upper = body.upper()
    funcs = set(_FUNC_RE.findall(upper))
    ranges = _RANGE_RE.findall(body)
    has_range = bool(ranges)
    has_cross_sheet = bool(_CROSS_SHEET_RE.search(body))
    positional = funcs & POSITIONAL_FUNCTIONS

    # A range read by a function that picks a position rather than summarising
    # is the case that goes silently wrong when rows move.
    if positional:
        return (
            "tier_2",
            "reads a range by position (" + ",".join(sorted(positional))
            + ") — extending it would change which row is read",
            {},
        )

    # A reference pinned to ONE record, beside however safe the rest looks. If
    # the data's row count or order changes this silently reads a DIFFERENT
    # record, which is the failure nobody sees — so it is flagged even when
    # every range around it is a clean aggregate.
    pinned = fixed_record_refs(body)
    if pinned:
        return (
            "tier_2",
            "pinned to specific record(s) " + ", ".join(pinned)
            + " — if the data's row count or order changes this silently reads a "
            "DIFFERENT record. NEEDS HUMAN REVIEW.",
            {},
        )

    aggregated, loose = aggregated_ranges(formula)
    if aggregated and not loose:
        aggregates = sorted(funcs & SAFE_AGG_FUNCTIONS)
        others = sorted(funcs - SAFE_AGG_FUNCTIONS)
        reason = (
            f"aggregate ({','.join(aggregates)}) over a range — safe to regenerate "
            "against a new row count"
        )
        if others:
            # Said out loud: a reviewer seeing IFERROR in an auto-regenerated
            # formula should know it was considered, not overlooked.
            reason += f"; {','.join(others)} operate on its result, not on the range"
        return ("tier_1", reason, {"ranges": aggregated, "functions": aggregates})

    if loose:
        return (
            "tier_2",
            "range not read by a recognized aggregate: " + ",".join(sorted(set(loose))),
            {},
        )
    if funcs - SAFE_AGG_FUNCTIONS and has_range:
        return (
            "tier_2",
            "uses non-aggregate/unrecognized function(s): "
            + ",".join(sorted(funcs - SAFE_AGG_FUNCTIONS)),
            {},
        )
    if has_cross_sheet and not has_range:
        return ("tier_2", "single fixed cross-sheet cell reference — verify once by hand", {})
    if has_range:
        return ("tier_2", "bare range reference without a recognized aggregate", {})
    return ("tier_3", "self-contained/static — never regenerated", {})


def _column_runs(col: str, rowmap: dict[int, dict[str, Any]]) -> list[dict[str, Any]]:
    """Candidate fill-down runs in ONE column, before any length rule.

    A run is a maximal set of cells in that column that share a formula SHAPE
    and sit a CONSTANT number of rows apart, in which every step is the one
    above filled down by exactly one row.

    Segmenting by shape and step first is what makes this correct on a real
    template. A block is routinely bounded by a different kind of formula — a
    totals row `=SUM(E6:E10)` directly under the mirror it totals. That row is
    a natural BOUNDARY, not a violation: a different shape simply ends the
    segment and the row classifies on its own.

    Within one segment a jumbled offset IS the signature of hand-wiring (refs
    running ...L6, L7, L3, L4, L5), and so is a step that advances more than
    one record per cell — a block of those regenerated against a new row count
    would read past the end of the data. Either refuses the whole segment
    rather than splitting it into a "clean" sub-block, and its cells fall back
    to per-cell classification (typically Tier 2)."""
    rows = sorted(rowmap)
    if not rows:
        return []

    def formula(row: int) -> str:
        return rowmap[row]["formula"]

    # Maximal segments: same shape, and a step that does not change mid-run.
    segments: list[tuple[list[int], int]] = []
    current = [rows[0]]
    step: int | None = None
    for prev, row in zip(rows, rows[1:]):
        gap = row - prev
        joins = (gap <= MAX_ROW_STEP
                 and _shape(formula(row)) == _shape(formula(prev))
                 and (step is None or gap == step))
        if joins:
            current.append(row)
            step = gap
        else:
            segments.append((current, step or 1))
            current = [row]
            step = None
    segments.append((current, step or 1))

    runs: list[dict[str, Any]] = []
    for seg, seg_step in segments:
        if len(seg) < MIN_WIDE_MIRROR_ROWS:
            continue
        # One record per cell, every cell, or this is not a fill-down.
        if any(_row_shift(formula(a), formula(b)) != 1 for a, b in zip(seg, seg[1:])):
            continue
        runs.append({
            "sheet": rowmap[seg[0]]["sheet"],
            "column": col,
            "start_row": seg[0],
            "end_row": seg[-1],
            "rows": len(seg),
            "row_step": seg_step,
            "template_formula": formula(seg[0]),
            "cells": [rowmap[r]["coord"] for r in seg],
        })
    return runs


def _group_adjacent_columns(runs: list[dict[str, Any]]) -> None:
    """Mark runs that are one fill-down region written across several columns.

    A region laid out side by side is one thing a person decided, and counting
    it as three is how an approval screen turns into a wall. The columns are
    grouped, not merged: each keeps its own formula, because adjacent columns
    of the same region rarely compute the same thing."""
    by_extent: dict[tuple[Any, ...], list[dict[str, Any]]] = defaultdict(list)
    for run in runs:
        by_extent[(run["sheet"], run["start_row"], run["end_row"],
                   run["row_step"])].append(run)

    for members in by_extent.values():
        members.sort(key=lambda r: column_index_from_string(r["column"]))
        group: list[dict[str, Any]] = []
        for run in members:
            index = column_index_from_string(run["column"])
            if group and index != column_index_from_string(group[-1]["column"]) + 1:
                _label_group(group)
                group = []
            group.append(run)
        _label_group(group)


def _label_group(group: list[dict[str, Any]]) -> None:
    if not group:
        return
    columns = [run["column"] for run in group]
    name = (f"{group[0]['sheet']}!{columns[0]}{group[0]['start_row']}"
            f":{columns[-1]}{group[0]['end_row']}")
    for run in group:
        run["group_id"] = name
        run["group_columns"] = columns


def _carries_its_own_weight(run: dict[str, Any]) -> bool:
    """Whether a run is evidence of a fill-down or just a coincidence.

    Three rows in one column is the bar. A shorter run clears it only as part
    of a wide region: the same two rows repeated across adjacent columns is a
    pattern somebody filled, and judging each column alone left every one of
    those cells flagged."""
    if run["rows"] >= MIN_MIRROR_ROWS:
        return True
    return len(run.get("group_columns") or []) >= MIN_GROUP_COLUMNS


def detect_row_mirror_blocks(cells: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Find Tier-1b row-mirror blocks among one sheet's formula cells.

    A block is how a template lays one output row per data row, and it is
    regenerated by extending or shrinking it to the new row count — as ONE
    unit, never one flag per cell per row. Detection is purely structural: no
    sheet, column or cell name is referenced anywhere in it."""
    by_col: dict[str, dict[int, dict[str, Any]]] = defaultdict(dict)
    for fc in cells:
        by_col[fc["col"]][fc["row"]] = fc

    runs: list[dict[str, Any]] = []
    for col, rowmap in by_col.items():
        runs.extend(_column_runs(col, rowmap))

    _group_adjacent_columns(runs)
    blocks = [run for run in runs if _carries_its_own_weight(run)]
    blocks.sort(key=lambda b: (b["start_row"], column_index_from_string(b["column"])))
    return blocks


def header_row_index(ws) -> int:
    """Index of the first row with >= 2 populated cells (skips a single-cell title
    banner), else the first populated row, else 1."""
    first_populated = None
    for row in ws.iter_rows():
        non_empty = [c for c in row if c.value is not None and str(c.value).strip() != ""]
        if non_empty:
            if first_populated is None:
                first_populated = non_empty[0].row
            if len(non_empty) >= 2:
                return non_empty[0].row
    return first_populated or 1


def header_labels(ws, header_row: int) -> dict[str, str]:
    """{column_letter: header label} for a given header row (blank cells omitted)."""
    out: dict[str, str] = {}
    for cell in ws[header_row]:
        if cell.value is not None and str(cell.value).strip() != "":
            out[cell.column_letter] = str(cell.value)
    return out


def _normalized_cell_type(value) -> str | None:
    """Coarse type of a cell value for column-consistency checks: None (empty),
    'formula', 'num' (int/float/bool), 'date', or 'str'. int vs float are the same
    'num' — real data columns freely mix them."""
    if value is None or (isinstance(value, str) and value.strip() == ""):
        return None
    if isinstance(value, str) and value.startswith("="):
        return "formula"
    if isinstance(value, bool):
        return "num"
    if isinstance(value, (int, float)):
        return "num"
    if isinstance(value, (datetime, date, time)):
        return "date"
    return "str"


def _looks_like_data_table(ws, header_row: int) -> bool:
    """A structural data-vs-parameter test (independent of cell count).

    True when the header row (>= 2 named columns) is followed by a CONTIGUOUS run
    of >= MIN_DATA_TABLE_ROWS record rows — each filling a majority of the header
    columns — AND the columns are type-consistent going DOWN (>= DATA_COL_CONSISTENCY
    of them). A scattered label/value parameter sheet (blank rows / section headers
    break the run; its value column mixes types) fails and is classified 'parameter'."""
    header_cols = [c.column_letter for c in ws[header_row]
                   if c.value is not None and str(c.value).strip() != ""]
    width = len(header_cols)
    if width < 2:
        return False
    col_idxs = [column_index_from_string(c) for c in header_cols]
    need = max(2, (width + 1) // 2)          # a record row fills a majority of cols

    record_rows: list[int] = []
    r = header_row + 1
    while r <= ws.max_row:
        present = sum(1 for ci in col_idxs
                      if _normalized_cell_type(ws.cell(row=r, column=ci).value) is not None)
        if present < need:                    # blank row / section header ends the run
            break
        record_rows.append(r)
        r += 1
    needed_rows = (MIN_WIDE_TABLE_ROWS if width >= WIDE_HEADER_COLUMNS
                   else MIN_DATA_TABLE_ROWS)
    if len(record_rows) < needed_rows:
        return False

    consistent = 0
    for ci in col_idxs:
        types = {t for rr in record_rows
                 if (t := _normalized_cell_type(ws.cell(row=rr, column=ci).value)) is not None}
        if len(types) <= 1:
            consistent += 1
    return (consistent / width) >= DATA_COL_CONSISTENCY


def _scan_sheet(ws) -> dict[str, Any]:
    """Per-sheet stats, role, header, and raw formula cells."""
    formula_cells: list[dict[str, Any]] = []
    value_count = 0
    for row in ws.iter_rows():
        for cell in row:
            ftext = _formula_text(cell)
            if ftext is not None:
                formula_cells.append({
                    "sheet": ws.title, "coord": cell.coordinate,
                    "col": cell.column_letter, "row": cell.row, "formula": ftext,
                })
            elif cell.value is not None and str(cell.value).strip() != "":
                value_count += 1

    formula_count = len(formula_cells)
    populated = formula_count + value_count
    ratio = (formula_count / populated) if populated else 0.0

    hdr_idx = header_row_index(ws)
    header_by_col: dict[str, str] = {}
    header: list[str] = []
    for cell in ws[hdr_idx]:
        label = "" if cell.value is None else str(cell.value)
        header.append(label)
        if label.strip():
            header_by_col[cell.column_letter] = label

    # A formula-heavy sheet is "formula"; otherwise distinguish a real record
    # table ("data") from scattered config ("parameter") STRUCTURALLY — not by
    # cell count, which cannot tell a small data table from a parameter sheet.
    if formula_count and ratio >= FORMULA_SHEET_RATIO:
        role = "formula"
    elif _looks_like_data_table(ws, hdr_idx):
        role = "data"
    else:
        role = "parameter"

    return {
        "name": ws.title, "role": role, "formula_cells": formula_cells,
        "formula_count": formula_count, "value_count": value_count,
        "formula_ratio": round(ratio, 4), "header_row": hdr_idx,
        "header": header, "header_by_col": header_by_col,
    }


def _fingerprint(sheets: list[dict[str, Any]]) -> str:
    """Stable hash of the template's SHAPE — invariant to row count. Includes ALL
    formula cells (row-normalized), so a mirror block of any length collapses to a
    single pattern."""
    parts: list[str] = []
    for sheet in sheets:
        parts.append("SHEET:" + sheet["name"])
        parts.append("HDR:" + "|".join(sheet["header"]))
        patterns = {
            _DIGITS_RE.sub("#", fc["coord"]) + "=" + _DIGITS_RE.sub("#", fc["formula"])
            for fc in sheet["formula_cells"]
        }
        parts.extend("F:" + p for p in sorted(patterns))
    return hashlib.sha256("\n".join(parts).encode("utf-8")).hexdigest()


def _sheet_aliases(sheets: list[dict[str, Any]]) -> dict[str, str]:
    """Each sheet's name mapped to a token for its POSITION in the workbook.

    Not a number, because the fingerprint normalises digits away and two
    positions would collapse into one token."""
    return {s["name"].upper(): "~" + get_column_letter(i + 1)
            for i, s in enumerate(sheets)}


def _anonymise_sheets(formula: str, aliases: dict[str, str]) -> str:
    """Replace every sheet name a formula refers to with that sheet's position.
    A name the workbook does not have (an external reference) becomes one
    token, so it still counts as a difference without naming anything."""
    def _repl(m: re.Match) -> str:
        name = m.group(1) or m.group(2)
        return aliases.get(name.upper(), "~?") + "!"

    return _SHEET_QUALIFIER_RE.sub(_repl, formula)


def _shape_fingerprint(sheets: list[dict[str, Any]]) -> str:
    """The same hash as _fingerprint, blind to what the sheets are CALLED.

    Renaming a tab changes a template's name in two places at once — the sheet
    list and every formula that reads across to it — so an approved template
    came back unrecognised and had to be approved again, which is a person
    re-reading a workbook that did not change. Positions carry the structure;
    the names carry nothing the headers and formulas do not."""
    aliases = _sheet_aliases(sheets)
    parts: list[str] = []
    for index, sheet in enumerate(sheets):
        parts.append("SHEET:" + get_column_letter(index + 1))
        # A header cell can hold a formula, which names a sheet like any other.
        parts.append("HDR:" + "|".join(_anonymise_sheets(label, aliases)
                                       for label in sheet["header"]))
        patterns = {
            _DIGITS_RE.sub("#", fc["coord"]) + "="
            + _DIGITS_RE.sub("#", _anonymise_sheets(fc["formula"], aliases))
            for fc in sheet["formula_cells"]
        }
        parts.extend("F:" + p for p in sorted(patterns))
    return hashlib.sha256("\n".join(parts).encode("utf-8")).hexdigest()


def scan_workbook(wb, template_name: str) -> dict[str, Any]:
    """Classify an already-open workbook. Pure — no I/O."""
    sheets = [_scan_sheet(ws) for ws in wb.worksheets]

    tab_roles = {s["name"]: s["role"] for s in sheets}
    header_by_col = {s["name"]: s["header_by_col"] for s in sheets}
    header_rows = {s["name"]: s["header_row"] for s in sheets}
    tiers: dict[str, list[dict[str, Any]]] = {
        "tier_1": [], "tier_1b": [], "tier_2": [], "tier_3": []
    }

    for s in sheets:
        blocks = detect_row_mirror_blocks(s["formula_cells"])
        claimed = {coord for b in blocks for coord in b["cells"]}
        tiers["tier_1b"].extend(blocks)
        for fc in s["formula_cells"]:
            if fc["coord"] in claimed:
                continue
            tier, reason, meta = classify_formula(fc["formula"])
            entry = {"sheet": fc["sheet"], "cell": fc["coord"], "formula": fc["formula"],
                     "reason": reason}
            if tier == "tier_1":
                entry["ranges"] = meta["ranges"]
                entry["functions"] = meta["functions"]
            if tier == "tier_2":
                # Split the catch-all bucket by ACTUAL risk, so a reviewer sees the
                # few formulas that can silently go wrong — not every unrecognized one.
                pinned = fixed_record_refs(fc["formula"])
                entry["risk"] = "high" if pinned else "low"
                if pinned:
                    entry["fixed_refs"] = pinned
                    entry["reason"] = (
                        "pinned to specific record(s) " + ", ".join(pinned) +
                        " — if the data's row count or order changes this silently "
                        "reads a DIFFERENT record. NEEDS HUMAN REVIEW."
                    )
                else:
                    entry["reason"] = reason + " — not auto-regenerated, but nothing "
                    entry["reason"] += "in it depends on the row count (informational)"
            tiers[tier].append(entry)

    return {
        "template_name": template_name,
        "fingerprint": _fingerprint(sheets),
        # Matched when the exact one misses, so a renamed tab is not a new
        # template. Kept as a second key rather than replacing the first:
        # every template approved before this is stored under the exact one.
        "shape_fingerprint": _shape_fingerprint(sheets),
        "tab_roles": tab_roles,
        "header_by_col": header_by_col,
        "header_rows": header_rows,
        "formula_classification": tiers,
        "summary": {
            "sheets": len(sheets),
            "tier_1": len(tiers["tier_1"]),
            "tier_1b_blocks": len(tiers["tier_1b"]),
            "tier_1b_cells": sum(b["rows"] for b in tiers["tier_1b"]),
            "tier_2": len(tiers["tier_2"]),
            # the only number a human actually has to act on:
            "tier_2_needs_review": sum(1 for c in tiers["tier_2"] if c.get("risk") == "high"),
            "tier_3": len(tiers["tier_3"]),
        },
        "sheets": [
            {k: s[k] for k in ("name", "role", "formula_count", "value_count",
                               "formula_ratio", "header_row", "header")}
            for s in sheets
        ],
    }


def scan_file(path: str) -> dict[str, Any]:
    """Load an .xlsx from disk and classify it. Keeps formulas (data_only=False)."""
    import os

    wb = openpyxl.load_workbook(path, data_only=False)
    name = os.path.splitext(os.path.basename(path))[0]
    try:
        return scan_workbook(wb, name)
    finally:
        wb.close()


def scan_bytes(data: bytes, template_name: str) -> dict[str, Any]:
    """Classify an .xlsx given its raw bytes (e.g. a file uploaded in chat).
    Identical classification to scan_file — both open the workbook and delegate to
    scan_workbook; only the source (BytesIO vs path) differs."""
    import io

    wb = openpyxl.load_workbook(io.BytesIO(data), data_only=False)
    try:
        return scan_workbook(wb, template_name)
    finally:
        wb.close()
