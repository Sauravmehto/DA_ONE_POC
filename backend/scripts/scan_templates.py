"""What the template scanner makes of real workbooks.

The Report Builder can only regenerate what it can prove it understands, and
"prove" is a set of rules. This prints what those rules currently say about
every template in test_fixtures/templates, so a change to them can be judged
rather than guessed at:

    python scripts/scan_templates.py              # the summary table
    python scripts/scan_templates.py --flags      # why each cell was flagged
    python scripts/scan_templates.py --cells 20   # the flagged formulas themselves

The number that matters is not how many cells are flagged but how many are
flagged NEEDLESSLY — a wall of flags is how a reviewer stops reading, and a
reviewer who stops reading is how a wrong formula gets approved.

Add a workbook by dropping it in that folder. See its README for the truth
file that says what is actually true of one.
"""

from __future__ import annotations

import argparse
import json
import pathlib
import re
import sys
import warnings
from collections import Counter

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))

warnings.filterwarnings("ignore", category=UserWarning, module="openpyxl")

from app.engine import excel_template_scanner as scanner  # noqa: E402

TEMPLATES = pathlib.Path(__file__).resolve().parent.parent / "test_fixtures" / "templates"
CALL = re.compile(r"([A-Z][A-Z0-9_.]*)\s*\(")


def scan_all(folder: pathlib.Path) -> list[tuple[str, dict]]:
    if not folder.is_dir():
        sys.exit(f"No templates at {folder}.")
    out = []
    for path in sorted(folder.glob("*.xlsx")):
        try:
            out.append((path.name, scanner.scan_file(str(path))))
        except Exception as exc:  # noqa: BLE001 - a workbook that will not open is a result
            print(f"{path.name}: could not be read — {exc}")
    return out


def truth_for(name: str) -> dict | None:
    path = TEMPLATES / f"{pathlib.Path(name).stem}.truth.json"
    if not path.is_file():
        return None
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        print(f"  ({path.name} could not be read: {exc})")
        return None


def summarise(scans: list[tuple[str, dict]]) -> None:
    print(f"{'template':44s} {'sheets':>6} {'auto':>6} {'blocks':>7} {'flagged':>8} "
          f"{'review':>7} {'static':>7}")
    print("-" * 90)
    for name, scan in scans:
        s = scan["summary"]
        print(f"{name[:44]:44s} {s['sheets']:6} {s['tier_1']:6} {s['tier_1b_blocks']:7} "
              f"{s['tier_2']:8} {s['tier_2_needs_review']:7} {s['tier_3']:7}")
    print()
    print("auto    — regenerated by rule (an aggregate over a range)")
    print("blocks  — fill-down runs, regenerated as one unit")
    print("flagged — handed to a person; 'review' is the subset that can silently go wrong")


def explain(scans: list[tuple[str, dict]], show_cells: int) -> None:
    for name, scan in scans:
        flagged = scan["formula_classification"]["tier_2"]
        print(f"\n{name}  —  {len(flagged)} flagged")

        functions: Counter[str] = Counter()
        for cell in flagged:
            for func in set(CALL.findall(cell["formula"].upper())):
                functions[func] += 1
        if functions:
            print("  functions involved: "
                  + ", ".join(f"{f}×{n}" for f, n in functions.most_common(10)))

        reasons = Counter(cell["reason"].split("—")[0].strip()[:64] for cell in flagged)
        for reason, count in reasons.most_common():
            print(f"   {count:5}  {reason}")

        truth = truth_for(name)
        if truth:
            print(f"  truth recorded: data sheet {truth.get('data_sheet')!r}, "
                  f"{len(truth.get('regenerates') or [])} cells that re-extend, "
                  f"{len(truth.get('must_not_touch') or [])} that must not be touched")

        for cell in flagged[:show_cells]:
            print(f"    {cell['sheet']}!{cell['cell']:7s} {cell['formula'][:100]}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--folder", type=pathlib.Path, default=TEMPLATES)
    parser.add_argument("--flags", action="store_true", help="why cells were flagged")
    parser.add_argument("--cells", type=int, default=0, help="show N flagged formulas")
    args = parser.parse_args()

    scans = scan_all(args.folder)
    if not scans:
        sys.exit(f"No .xlsx templates in {args.folder}.")
    summarise(scans)
    if args.flags or args.cells:
        explain(scans, args.cells)


if __name__ == "__main__":
    main()
